/**
 * The gemstone guide — every type of gem the store works with, grouped the way
 * Indian buyers think about them. `productSlug` links into /data/products.ts;
 * gems without a listed product point shoppers to an expert instead.
 */

export type GemGroup = 'navratna' | 'uparatna' | 'crystal';

export interface GemTypeInfo {
  slug: string;
  name: string;
  hindi: string;
  group: GemGroup;
  planet: string;
  /** Zodiac signs (English) traditionally suited to the stone */
  rashi: string[];
  colour: string;
  /** Mohs hardness */
  hardness: string;
  origin: string;
  wear: { finger: string; metal: string; day: string };
  benefits: string[];
  /** Cheaper stones worn for the same planet */
  substitutes?: string[];
  organic?: boolean;
  productSlug?: string;
  /** Label for the shop button when the linked product is a substitute */
  shopLabel?: string;
  art: GemArt;
}

