/* ------------------------------ Query helpers ------------------------------ */
/* Swap these for API calls when a backend is added — nothing else changes.    */

export function getAllProducts(): Product[] {
  return products;
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((product) => product.slug === slug);
}

export function getProductsByCategory(category: string): Product[] {
  return products.filter((product) => product.category === category);
}

export function getFeaturedProducts(): Product[] {
  return products.filter((product) => product.featured);
}

export function getBestsellers(limit = 8): Product[] {
  return products.filter((product) => product.bestseller).slice(0, limit);
}

export function getNewArrivals(limit = 4): Product[] {
  return [...products].sort((a, b) => Date.parse(b.createdAt) - Date.parse(a.createdAt)).slice(0, limit);
}

export function getProductsByRashi(rashi: string): Product[] {
  return products.filter((product) => product.rashi.includes(rashi));
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  const sameCategory = products.filter(
    (candidate) => candidate.slug !== product.slug && candidate.category === product.category,
  );
  const sameRashi = products.filter(
    (candidate) =>
      candidate.slug !== product.slug &&
      candidate.category !== product.category &&
      candidate.rashi.some((sign) => product.rashi.includes(sign)),
  );
  return [...sameCategory, ...sameRashi].slice(0, limit);
}

export function searchProducts(query: string): Product[] {
  const term = query.trim().toLowerCase();
  if (!term) return [];
  return products.filter((product) =>
    [product.name, product.hindiName, product.gemType, product.planet, product.category, product.shortDescription]
      .filter(Boolean)
      .some((field) => String(field).toLowerCase().includes(term)),
  );
}

/** Distinct gemstone types, used to build the shop filter sidebar. */
export function getGemTypes(): string[] {
  return Array.from(new Set(products.map((product) => product.gemType))).sort();
}

export function getPriceBounds(): { min: number; max: number } {
  const prices = products.map((product) => product.price);
  return { min: Math.min(...prices), max: Math.max(...prices) };
}
